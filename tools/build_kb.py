"""Turn the text pulled from triciafriedman.com/ai-assessment-frameworks/ into
frameworks.json (for the page) and netlify/edge-functions/partner/kb.js (for the bot).
Re-run after the library page changes: re-save tools/source-page-text.txt first."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
lines = [l.strip() for l in (root/'tools/source-page-text.txt').read_text().splitlines() if l.strip()]
KINDS = ['Written for AI', 'Grading and assessment design', 'Long-running alternatives']
start = next(i for i,l in enumerate(lines) if l.startswith('2026 [#af-2026]'))
end = next(i for i,l in enumerate(lines) if l == 'How this list was checked')
entries, cur = [], None
for l in lines[start:end]:
    kind = next((k for k in KINDS if k in l), None)
    if kind and not l.startswith('Learning is for') and '[' not in l:
        date, region = l.split(kind, 1)
        date = re.sub(r'^2026 \[#af-2026\].*?2026 12', '', date).strip() if '[#af-' in date else date.strip()
        cur = {'date': date, 'type': kind, 'region': region.strip(), 'title': None, 'url': None,
               'by': None, 'summary': None, 'also': [], 'purposes': []}
        entries.append(cur); continue
    if cur is None: continue
    m = re.match(r'^(.*) \[(https?://[^\]]+)\]$', l)
    if cur['title'] is None and m:
        cur['title'], cur['url'] = m.group(1), m.group(2); continue
    if l.startswith('Also: '):
        cur['also'] = [{'label': a, 'url': u} for a,u in re.findall(r'(.+?) \[(https?://[^\]]+)\](?: · )?', l[6:])]; continue
    if l.startswith('Learning is for: '):
        cur['purposes'] = [p.strip() for p in l[17:].split('·')]; continue
    if re.match(r'^(\d{4}|2017 to 2022|2001 to 2016|Before 2001) \d+$', l): continue
    if cur['by'] is None: cur['by'] = l
    elif cur['summary'] is None: cur['summary'] = l
for i,e in enumerate(entries,1): e['id'] = i
assert len(entries) == 50, len(entries)
assert all(e['title'] and e['summary'] and e['purposes'] for e in entries)
(root/'frameworks.json').write_text(json.dumps(entries, ensure_ascii=False, indent=1))
(root/'netlify/edge-functions/partner/kb.js').write_text('// Generated by tools/build_kb.py. Do not edit by hand.\nexport const FRAMEWORKS = ' + json.dumps(entries, ensure_ascii=False) + ';\n')
print(len(entries), 'entries'); print(json.dumps(entries[0], indent=1)); print(entries[-1]['title'], entries[23]['date'])
